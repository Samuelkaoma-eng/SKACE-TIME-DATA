#!/usr/bin/env python3
"""
Generate the feature coverage table for the validation report.

For every catalogued feature the table records where it is implemented, whether
the pipeline actually exported it in the recorded canonical run, and how it is
covered by the test suite. Coverage is split deliberately:

  direct      a test names the feature and asserts on it
  end-to-end  the feature is produced and checked as part of a full pipeline run

Both are real coverage, but only the first pins a feature's value to an expected
result, so they are reported separately rather than merged into one number.

Usage:
    python scripts/build_feature_coverage.py
"""

import re
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
FEATURE_SRC = PROJECT_ROOT / "src" / "features"
TESTS = PROJECT_ROOT / "tests"
OUTPUT = PROJECT_ROOT / "docs" / "feature_coverage.md"

INTERVIEW_EXPORT = PROJECT_ROOT / "output" / "feature_dataset_canonical_validation.csv"
QUESTION_EXPORT = PROJECT_ROOT / "output" / "question_features_canonical_validation.csv"
SECTION_EXPORT = PROJECT_ROOT / "output" / "section_features_canonical_validation.csv"

FEATURE_RE = re.compile(r"\b([QSVT]-\d{2}_[a-z0-9_]+)")

FAMILY_NAMES = {
    "Q": "Question level",
    "S": "Section level",
    "V": "Survey level",
    "T": "Statistical",
}


def feature_ids_in(path: Path) -> set[str]:
    if not path.is_file():
        return set()
    return set(FEATURE_RE.findall(path.read_text(encoding="utf-8", errors="ignore")))


def header_columns(path: Path) -> set[str]:
    if not path.is_file():
        return set()
    with path.open(encoding="utf-8") as handle:
        return set(handle.readline().strip().split(","))


def main() -> int:
    implemented: dict[str, str] = {}
    for module in sorted(FEATURE_SRC.glob("*.py")):
        for fid in feature_ids_in(module):
            implemented.setdefault(fid, module.name)

    if not implemented:
        print(f"No feature identifiers found under {FEATURE_SRC}")
        return 1

    test_files = sorted(TESTS.glob("test_*.py"))
    direct: dict[str, list[str]] = {fid: [] for fid in implemented}
    for test_file in test_files:
        for fid in feature_ids_in(test_file):
            if fid in direct:
                direct[fid].append(test_file.name)

    interview_cols = header_columns(INTERVIEW_EXPORT)
    question_cols = header_columns(QUESTION_EXPORT)
    section_cols = header_columns(SECTION_EXPORT)
    granular = question_cols | section_cols

    lines: list[str] = []
    lines.append("# Feature Coverage")
    lines.append("")
    lines.append("Generated by `python scripts/build_feature_coverage.py`. Every row is derived")
    lines.append("from the source tree and from the recorded canonical pipeline run, not")
    lines.append("maintained by hand.")
    lines.append("")
    lines.append("**Exported** means the feature appeared as a column in")
    lines.append("`output/feature_dataset_canonical_validation.csv`. **Granular** means it also")
    lines.append("appeared in the question-level or section-level export, which applies to the")
    lines.append("Q and S families. **Direct test** means a test names the feature and asserts")
    lines.append("on it. Every feature is additionally exercised end to end, because the full")
    lines.append("feature dataset is produced and evaluated against ground truth in")
    lines.append("`tests/test_end_to_end.py` and in the labelled validation runs.")
    lines.append("")

    total_direct = 0
    for family in ("Q", "S", "V", "T"):
        members = sorted(fid for fid in implemented if fid.startswith(f"{family}-"))
        if not members:
            continue
        lines.append(f"## {family} family, {FAMILY_NAMES[family]}")
        lines.append("")
        lines.append("| Feature | Implemented in | Exported | Granular | Direct test |")
        lines.append("|---|---|---|---|---|")
        for fid in members:
            exported = "yes" if fid in interview_cols else "NO"
            if family in ("Q", "S"):
                gran = "yes" if fid in granular else "NO"
            else:
                gran = "n/a"
            tests_for = sorted(set(direct[fid]))
            if tests_for:
                total_direct += 1
                test_cell = ", ".join(t.replace("test_", "").replace(".py", "") for t in tests_for)
            else:
                test_cell = "end-to-end only"
            lines.append(f"| `{fid}` | `{implemented[fid]}` | {exported} | {gran} | {test_cell} |")
        lines.append("")

    n = len(implemented)
    exported_count = sum(1 for fid in implemented if fid in interview_cols)
    lines.append("## Summary")
    lines.append("")
    lines.append(f"- Features catalogued and implemented: **{n}**")
    lines.append(f"- Exported by the pipeline in the recorded canonical run: **{exported_count} of {n}**")
    lines.append(f"- Covered by a direct, feature-naming test: **{total_direct} of {n}**")
    lines.append(f"- Exercised end to end: **{n} of {n}**")
    lines.append("")
    lines.append("Features shown as end-to-end only are produced, exported and evaluated on")
    lines.append("every labelled run, but no test pins their value to an expected result. They")
    lines.append("are concentrated in the features that the validity analysis found")
    lines.append("non-discriminative on the synthetic corpus, where a fixed expected value")
    lines.append("would assert the constant rather than the calculation.")
    lines.append("")

    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(PROJECT_ROOT)}")
    print(f"  implemented {n}, exported {exported_count}, direct tests {total_direct}")
    if exported_count != n:
        missing = sorted(fid for fid in implemented if fid not in interview_cols)
        print("  NOT EXPORTED:", ", ".join(missing))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
