#!/usr/bin/env python3
"""
Measure the prevalence envelope: how detection degrades as anomalies stop
being a minority of the batch.

The class imbalance sweep in the robustness round stops at 30 percent. This
extends it to 90 percent, at both difficulties and at two batch sizes, on the
held-out seeds 7 and 99 only. Every other setting is the default detector
configuration, so the result describes the evaluated system.

Datasets are regenerated into data/prevalence_envelope/ (not committed) and
evaluated in SurveyCTO format. Per-run metrics and a summary averaged over the
two seeds are written to output/prevalence_envelope/.

Usage:
    python scripts/run_prevalence_envelope.py
"""

import json
import subprocess
import sys
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_ROOT = PROJECT_ROOT / "data" / "prevalence_envelope"
OUTPUT_DIR = PROJECT_ROOT / "output" / "prevalence_envelope"
RUN_DIR = OUTPUT_DIR / "runs"

RATIOS = [0.05, 0.10, 0.20, 0.30, 0.40, 0.50, 0.60, 0.70, 0.80, 0.90]
SEEDS = [7, 99]
SIZES = [500, 100]
DIFFICULTIES = ["canonical", "stress"]
ANOMALY_TYPES = ["fabricated", "speeding", "disengaged"]


def run(cmd: list[str], description: str) -> None:
    print(description, flush=True)
    result = subprocess.run(cmd, cwd=PROJECT_ROOT, stdout=subprocess.DEVNULL)
    if result.returncode != 0:
        print(f"FAILED: {description}")
        raise SystemExit(result.returncode)


def main() -> int:
    py = sys.executable
    gen = PROJECT_ROOT / "tests" / "generate_benchmark_datasets.py"
    pipe = PROJECT_ROOT / "run_pipeline.py"
    RUN_DIR.mkdir(parents=True, exist_ok=True)

    rows = []
    for size in SIZES:
        for difficulty in DIFFICULTIES:
            for seed in SEEDS:
                for ratio in RATIOS:
                    label = f"n{size}_{difficulty}_seed{seed}_r{round(ratio * 100):02d}"
                    ds = DATA_ROOT / label
                    run(
                        [py, str(gen), "--dataset-size", str(size), "--seed", str(seed),
                         "--anomaly-ratio", str(ratio), "--difficulty", difficulty,
                         "--output-dir", str(ds)],
                        f"Generate {label}",
                    )
                    run(
                        [py, str(pipe),
                         "--inputs", str(ds / "audit_logs_surveycto.csv"),
                         "--ground-truth", str(ds / "ground_truth_labels.csv"),
                         "--label", label,
                         "--output-dir", str(RUN_DIR)],
                        f"Evaluate {label}",
                    )
                    metrics = json.loads((RUN_DIR / f"metrics_{label}.json").read_text(encoding="utf-8"))[0]
                    by_type = pd.read_csv(RUN_DIR / f"detection_by_type_{label}.csv").set_index("anomaly_type")
                    row = {
                        "label": label,
                        "size": size,
                        "difficulty": difficulty,
                        "seed": seed,
                        "prevalence": ratio,
                        "tp": metrics["true_positive"],
                        "fp": metrics["false_positive"],
                        "fn": metrics["false_negative"],
                        "tn": metrics["true_negative"],
                        "precision": metrics["precision"],
                        "recall": metrics["recall"],
                    }
                    for anomaly_type in ANOMALY_TYPES:
                        if anomaly_type in by_type.index:
                            row[f"recall_{anomaly_type}"] = float(by_type.loc[anomaly_type, "detection_rate"])
                        else:
                            row[f"recall_{anomaly_type}"] = float("nan")
                    rows.append(row)

    per_run = pd.DataFrame(rows)
    per_run.to_csv(OUTPUT_DIR / "envelope_runs.csv", index=False)

    # Seeds are pooled on confusion counts, so the summary precision and
    # recall are those of the two runs taken together, not a mean of ratios.
    pooled = per_run.groupby(["size", "difficulty", "prevalence"], as_index=False)[["tp", "fp", "fn", "tn"]].sum()
    pooled["precision"] = pooled["tp"] / (pooled["tp"] + pooled["fp"])
    pooled["recall"] = pooled["tp"] / (pooled["tp"] + pooled["fn"])
    per_class = per_run.groupby(["size", "difficulty", "prevalence"], as_index=False)[
        [f"recall_{anomaly_type}" for anomaly_type in ANOMALY_TYPES]
    ].mean()
    summary = pooled.merge(per_class, on=["size", "difficulty", "prevalence"])
    summary.to_csv(OUTPUT_DIR / "envelope_summary.csv", index=False, float_format="%.4f")

    lines = [
        "# Prevalence envelope",
        "",
        "Generated by `scripts/run_prevalence_envelope.py`. SurveyCTO format, default",
        "detector configuration, held-out seeds 7 and 99 pooled on confusion counts.",
        "Per-class recall is the mean over the two seeds.",
        "",
        "| Size | Difficulty | Prevalence | Precision | Recall | Fabricated | Speeding | Disengaged |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for record in summary.itertuples(index=False):
        lines.append(
            f"| {record.size} | {record.difficulty} | {record.prevalence:.0%} | {record.precision:.4f} | "
            f"{record.recall:.4f} | {record.recall_fabricated:.2f} | {record.recall_speeding:.2f} | "
            f"{record.recall_disengaged:.2f} |"
        )
    (OUTPUT_DIR / "envelope_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"\n{'=' * 80}\nPREVALENCE ENVELOPE\n{'=' * 80}")
    print("\n".join(lines[6:]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
